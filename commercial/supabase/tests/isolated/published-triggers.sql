CREATE OR REPLACE FUNCTION public.finalize_refresh_request_if_terminal()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_request_id uuid;
  v_pending_running int;
  v_cancelled int;
  v_failed int;
  v_completed int;
begin
  v_request_id := coalesce(new.request_id, old.request_id);
  if v_request_id is null then return new; end if;

  select
    count(*) filter (where status in ('pending','running')),
    count(*) filter (where status='cancelled'),
    count(*) filter (where status='failed'),
    count(*) filter (where status='completed')
  into v_pending_running,v_cancelled,v_failed,v_completed
  from (
    select status::text from public.monitor_jobs where request_id=v_request_id
    union all
    select status::text from public.historical_archive_jobs where request_id=v_request_id
    union all
    select status::text from public.import_v2_jobs where request_id=v_request_id
  ) x(status);

  if v_pending_running>0 then return new; end if;
  if v_cancelled>0 then return new; end if;

  update public.refresh_requests
  set terminal_status=case when v_failed>0 then 'failed' else 'completed' end,
      completed_job_count=v_completed,
      failed_job_count=v_failed,
      finalized_at=now(),
      updated_at=now()
  where id=v_request_id
    and finalized_at is null
    and cancel_requested_at is null;

  return new;
end
$function$;

CREATE OR REPLACE FUNCTION app.audit_result_change()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_athlete uuid;
  v_account uuid;
  v_uid uuid;
begin
  v_athlete := coalesce(new.athlete_id,old.athlete_id);
  select account_id into v_account from public.athletes where id=v_athlete;
  v_uid := auth.uid();

  insert into public.audit_log(account_id,athlete_id,user_id,entity_type,entity_id,action,old_data,new_data,source)
  values(
    v_account,
    v_athlete,
    v_uid,
    'result',
    coalesce(new.id,old.id),
    lower(tg_op),
    case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end,
    case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end,
    case when v_uid is null then 'monitor' else 'app' end
  );

  return coalesce(new,old);
end;
$function$;

CREATE OR REPLACE FUNCTION app.refresh_personal_best()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_athlete uuid;
  v_event uuid;
  v_course public.swim_course;
  v_best record;
begin
  v_athlete := coalesce(new.athlete_id, old.athlete_id);
  v_event := coalesce(new.event_id, old.event_id);
  v_course := coalesce(new.course, old.course);

  delete from public.personal_bests
  where athlete_id=v_athlete and event_id=v_event and course=v_course;

  select r.id, r.time_ms, r.result_date
    into v_best
  from public.results r
  where r.athlete_id=v_athlete
    and r.event_id=v_event
    and r.course=v_course
    and r.status='valid'
    and r.is_official=true
    and r.time_ms is not null
  order by r.time_ms asc, r.result_date asc, r.created_at asc
  limit 1;

  if v_best.id is not null then
    insert into public.personal_bests(athlete_id,event_id,course,result_id,time_ms,achieved_at)
    values(v_athlete,v_event,v_course,v_best.id,v_best.time_ms,v_best.result_date);
  end if;

  return coalesce(new,old);
end;
$function$;

